#!/bin/sh
# Render Formula/probitas.rb for a Probitas 2+ release from its SHA256SUMS.
#
# Usage: scripts/render-formula.sh <version> <SHA256SUMS file> > Formula/probitas.rb
#
# Probitas 2 ships a prebuilt binary per platform on the GitHub Release; the
# formula installs that binary and needs no Deno.
set -eu

version="$1"
sums="$2"
base="https://github.com/probitas-test/probitas/releases/download/v${version}"

sha() {
  hash=$(grep " probitas-$1.tar.gz\$" "$sums" | cut -d' ' -f1)
  if [ -z "$hash" ]; then
    echo "probitas-$1.tar.gz is not listed in $sums" >&2
    exit 1
  fi
  echo "$hash"
}

darwin_arm64=$(sha darwin-arm64)
darwin_x64=$(sha darwin-x64)
linux_arm64=$(sha linux-arm64)
linux_x64=$(sha linux-x64)

cat <<EOF
# typed: false
# frozen_string_literal: true

# Homebrew formula for Probitas CLI (generated by scripts/render-formula.sh)
# Install: brew install probitas-test/tap/probitas
class Probitas < Formula
  desc "Scenario-based test and workflow execution framework CLI"
  homepage "https://github.com/probitas-test/probitas"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/probitas-darwin-arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/probitas-darwin-x64.tar.gz"
      sha256 "${darwin_x64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/probitas-linux-arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/probitas-linux-x64.tar.gz"
      sha256 "${linux_x64}"
    end
  end

  def install
    bin.install "probitas"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/probitas --version")
  end
end
EOF
